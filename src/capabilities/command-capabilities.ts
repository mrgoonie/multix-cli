/**
 * What each multix command does, stated per command instead of guessed from
 * its name. Every leaf command is either here or in UTILITY_COMMANDS; a test
 * fails for a command in neither, so a new command must be classified.
 *
 * "provider-catalog" means the command passes any model id through. That says
 * nothing about whether a given id works: verified ids live in model-registry.ts.
 */

