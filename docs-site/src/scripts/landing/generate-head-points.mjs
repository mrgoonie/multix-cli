#!/usr/bin/env node
/**
 * Writes the placeholder point cloud for the landing hero into public/hero/:
 *
 *   head-points.bin    the points (format below)
 *   head-points.json   manifest: count, layout, region codes and label anchors
 *   head-poster.svg    a still, front-facing render of the same points, shown
 *                      when there is no JS, no WebGL or reduced motion
 *
 * The head is a procedural signed distance field sampled as horizontal
 * contour rings. A mesh made with multix can replace it as long as it is
 * written in the same format.
 *
 * Usage: node docs-site/src/scripts/landing/generate-head-points.mjs
 *
 * ── head-points.bin, version 1 ───────────────────────────────────────────
 * Little-endian, no header; `count` comes from head-points.json.
 *
 *   bytes [0, 12·count)          Float32 x, y, z for each point
 *   bytes [12·count, 13·count)   Uint8 region code for each point
 *
 * Coordinate frame: y up, +z toward the viewer, head centred on x = 0. The
 * renderer's camera expects the head to span roughly y ∈ [-1.7, 1.2] (neck
 * bottom to crown) and x, z ∈ [-0.9, 1.0]; points below y = -1.15 fade out.
 *
 * Region codes: 0 skin, 1 eyes, 2 ears, 3 mouth, 5 crown (lights up on
 * "create"). Codes 4 (sound waves) and 6 (creation sparks) are generated by
 * the renderer and must not appear in the file.
 *
 * Mesh order matters only for mobile, which draws every second point: keep
 * neighbouring points next to each other (ring by ring, or a shuffled order).
 * ─────────────────────────────────────────────────────────────────────────
 */

import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const outDir = fileURLToPath(new URL("../../../public/hero/", import.meta.url));

/* ---------- signed distance field of a stylised head ---------- */

const len = (x, y, z) => Math.hypot(x, y, z);
const ell = (px, py, pz, cx, cy, cz, rx, ry, rz) => {
  const x = px - cx;
  const y = py - cy;
  const z = pz - cz;
  const k0 = len(x / rx, y / ry, z / rz);
  const k1 = len(x / (rx * rx), y / (ry * ry), z / (rz * rz));
  return (k0 * (k0 - 1)) / (k1 || 1e-6);
};
const sph = (px, py, pz, cx, cy, cz, r) => len(px - cx, py - cy, pz - cz) - r;
const cap = (px, py, pz, ax, ay, az, bx, by, bz, r) => {
  const pax = px - ax;
  const pay = py - ay;
  const paz = pz - az;
  const bax = bx - ax;
  const bay = by - ay;
  const baz = bz - az;
  const h = Math.min(
    1,
    Math.max(0, (pax * bax + pay * bay + paz * baz) / (bax * bax + bay * bay + baz * baz)),
  );
  return len(pax - bax * h, pay - bay * h, paz - baz * h) - r;
};
const smin = (a, b, k) => {
  const h = Math.max(k - Math.abs(a - b), 0) / k;
  return Math.min(a, b) - h * h * k * 0.25;
};
const ssub = (a, b, k) => -smin(-a, b, k);

function head(x, y, z) {
  const ax = Math.abs(x);
  let d = ell(x, y, z, 0, 0.28, -0.05, 0.76, 0.86, 0.9); // cranium
  d = smin(d, ell(x, y, z, 0, -0.32, 0.16, 0.58, 0.62, 0.68), 0.3); // face mass
  d = smin(d, ell(x, y, z, 0, -0.84, 0.42, 0.26, 0.2, 0.22), 0.22); // chin
  d = smin(d, ell(ax, y, z, 0.42, -0.62, 0.3, 0.2, 0.2, 0.3), 0.2); // jaw corners
  d = smin(d, ell(ax, y, z, 0.44, -0.12, 0.52, 0.2, 0.17, 0.2), 0.18); // cheekbones
  d = smin(d, ell(x, y, z, 0, 0.24, 0.66, 0.6, 0.11, 0.2), 0.14); // brow ridge
  d = smin(d, cap(x, y, z, 0, 0.12, 0.8, 0, -0.26, 0.98, 0.075), 0.12); // nose bridge
  d = smin(d, sph(x, y, z, 0, -0.28, 0.96, 0.1), 0.1); // nose tip
  d = ssub(d, sph(ax, y, z, 0.29, 0.06, 0.82, 0.16), 0.07); // eye sockets
  d = Math.min(d, sph(ax, y, z, 0.29, 0.05, 0.69, 0.13)); // eyeballs
  d = smin(d, ell(x, y, z, 0, -0.52, 0.8, 0.22, 0.075, 0.12), 0.06); // lips
  d = ssub(d, ell(x, y, z, 0, -0.53, 0.92, 0.19, 0.012, 0.08), 0.02); // mouth line
  d = smin(d, ell(ax, y, z, 0.79, -0.04, -0.02, 0.09, 0.24, 0.15), 0.08); // ears
  d = smin(d, cap(x, y, z, 0, -0.75, -0.12, 0, -1.7, -0.2, 0.4), 0.3); // neck
  return d;
}

const EYE = [0.29, 0.05, 0.72];
const EAR = [0.81, -0.04, 0];
const MOUTH = [0, -0.52, 0.85];

/** Rings of dots at evenly spaced heights, each ray marched inward to the surface. */
function sampleHead(levels, perRing) {
  const xyz = [];
  const regions = [];
  for (let i = 0; i < levels; i++) {
    const y = 1.2 - (i / (levels - 1)) * 2.9;
    const offset = (i % 2) * 0.5;
    for (let j = 0; j < perRing; j++) {
      const a = ((j + offset) / perRing) * Math.PI * 2;
      const dx = Math.sin(a);
      const dz = Math.cos(a);
      const cz = -0.05;
      let r = 1.5;
      let hit = false;
      for (let s = 0; s < 64; s++) {
        const d = head(dx * r, y, cz + dz * r);
        if (d < 0.002) {
          hit = true;
          break;
        }
        r -= Math.max(d, 0.004);
        if (r < 0) break;
      }
      if (!hit) continue;
      const x = dx * r;
      const z = cz + dz * r;
      const ax = Math.abs(x);
      let region = 0;
      if (len(ax - EYE[0], y - EYE[1], z - EYE[2]) < 0.23) region = 1;
      else if (len(ax - EAR[0], y - EAR[1], z - EAR[2]) < 0.3) region = 2;
      else if (len(x - MOUTH[0], y - MOUTH[1], z - MOUTH[2]) < 0.24) region = 3;
      else if (y > 0.6) region = 5;
      xyz.push(x, y, z);
      regions.push(region);
    }
  }
  return { xyz: new Float32Array(xyz), regions: new Uint8Array(regions) };
}

/* ---------- poster: the renderer's resting camera, drawn as SVG dots ---------- */

const POSTER_W = 600;
const POSTER_H = 612; // the stage is 1 : 1.02
const smoothstep = (a, b, v) => {
  const t = Math.min(1, Math.max(0, (v - a) / (b - a)));
  return t * t * (3 - 2 * t);
};

function poster({ xyz }) {
  const aspect = POSTER_W / POSTER_H;
  const buckets = [[], [], [], []];
  const count = xyz.length / 3;
  for (let i = 0; i < count; i += 3) {
    const x = xyz[i * 3];
    const y = xyz[i * 3 + 1];
    const z = xyz[i * 3 + 2];
    if (z < -0.35) continue; // hidden behind the face in a front view
    const dist = 4.3 - z;
    const nx = (x * 2.45) / dist / aspect;
    const ny = ((y + 0.2) * 2.45) / dist;
    const depth = Math.min(1, Math.max(0, (z + 1) * 0.5));
    const alpha = (0.1 + 0.75 * depth * depth) * smoothstep(-1.7, -1.15, y);
    if (alpha < 0.06) continue;
    const px = ((nx + 1) / 2) * POSTER_W;
    const py = (1 - (ny + 1) / 2) * POSTER_H;
    const bucket = Math.min(3, Math.floor(alpha * 4.6));
    buckets[bucket].push(`M${px.toFixed(1)} ${py.toFixed(1)}h0`);
  }
  const groups = buckets
    .map((paths, b) =>
      paths.length
        ? `<path stroke-width="${(2.2 + b * 0.7).toFixed(1)}" stroke-opacity="${(0.18 + b * 0.24).toFixed(2)}" d="${paths.join("")}"/>`
        : "",
    )
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${POSTER_W} ${POSTER_H}" fill="none" stroke="#9aa2b2" stroke-linecap="round">${groups}</svg>\n`;
}

/* ---------- write ---------- */

const points = sampleHead(120, 200);
const count = points.regions.length;
const bin = new Uint8Array(count * 13);
// Float32Array is platform-endian; write through a DataView to guarantee little-endian.
const view = new DataView(bin.buffer);
for (let i = 0; i < points.xyz.length; i++) view.setFloat32(i * 4, points.xyz[i], true);
bin.set(points.regions, count * 12);

const manifest = {
  format: "multix-head-points",
  version: 1,
  count,
  layout: [
    { name: "position", type: "float32", components: 3, offset: 0 },
    { name: "region", type: "uint8", components: 1, offset: count * 12 },
  ],
  littleEndian: true,
  regions: { skin: 0, eyes: 1, ears: 2, mouth: 3, crown: 5 },
  // Points (same frame as the mesh) the sense labels hang from.
  anchors: { eyes: EYE, ears: EAR, mouth: MOUTH },
  source: "procedural signed distance field (placeholder)",
};

await mkdir(outDir, { recursive: true });
await Promise.all([
  writeFile(new URL("head-points.bin", `file://${outDir}`), bin),
  writeFile(
    new URL("head-points.json", `file://${outDir}`),
    `${JSON.stringify(manifest, null, 2)}\n`,
  ),
  writeFile(new URL("head-poster.svg", `file://${outDir}`), poster(points)),
]);
console.log(`public/hero: ${count} points, ${bin.byteLength} bytes`);
