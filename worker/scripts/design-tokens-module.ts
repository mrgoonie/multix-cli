/**
 * Turns the shared design tokens (docs-site/src/styles/tokens.css) into the
 * TypeScript module the Worker inlines into its pages. Kept free of file I/O
 * so the sync test can rebuild the module and compare it with the committed one.
 */

/** Strips comments and collapses whitespace without changing what the CSS means. */
export function minifyTokens(css: string): string {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{};:,>])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();
}

/** Emits the module already in Biome's format, so the generated file passes lint unchanged. */
export function designTokensModule(css: string): string {
  const tokens = minifyTokens(css);
  if (/['\\\n]/.test(tokens))
    throw new Error("design tokens must not contain quotes, backslashes or newlines");
  return `// Generated by scripts/sync-design-tokens.ts from docs-site/src/styles/tokens.css. Do not edit.
export const DESIGN_TOKENS =
  '${tokens}';
`;
}
